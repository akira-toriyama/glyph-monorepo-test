package onsen

// Etiquette is the washing area in the order it happens. The list is a
// sequence, not a ranking: a caller that sorts it teaches the wrong thing.
func Etiquette() []string {
	return []string{
		"leave your clothes and your big towel outside the water",
		"sit at a tap and wash before you get in",
		"rinse the soap off, all of it",
		"keep the small towel on your head, never in the bath",
	}
}
